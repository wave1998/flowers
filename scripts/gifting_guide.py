def gifting_for(flower):
    name = flower['name']
    meaning = flower['meaning']
    if name in SPECIFIC:
        recipients, occasions = SPECIFIC[name]
    elif flower.get('meaningKind') == 'historical' and any(word in meaning for word in ['易变', '高傲', '贫穷', '不幸']):
        recipients, occasions = ['花卉爱好者', '自己'], ['主题花艺', '园艺交流']
    else:
        match = next((values for words, values in GROUPS if any(word in name for word in words)), None)
        if match:
            recipients, occasions = match
        elif any(word in meaning for word in ['母爱', '亲恩', '敬爱']):
            recipients, occasions = ['母亲', '长辈', '老师'], ['表达感谢', '生日祝福', '表达关怀']
        elif any(word in meaning for word in ['相爱', '爱情', '告白', '甜蜜', '浪漫']):
            recipients, occasions = ['恋人', '伴侣'], ['纪念日', '生日', '表达心意']
        elif any(word in meaning for word in ['思念', '惦念', '眷恋', '记忆']):
            recipients, occasions = ['挚友', '恋人', '远方的亲友'], ['表达思念', '送别', '纪念日']
        elif any(word in meaning for word in ['感谢', '感恩', '真诚', '友谊']):
            recipients, occasions = ['朋友', '老师', '同事'], ['表达感谢', '生日祝福', '日常问候']
        elif any(word in meaning for word in ['团圆', '团聚', '丰盛', '同心']):
            recipients, occasions = ['家人', '朋友', '喜事之人'], ['家庭团聚', '乔迁', '庆祝']
        elif any(word in meaning for word in ['勇敢', '坚韧', '希望', '自信', '向前', '力量']):
            recipients, occasions = ['朋友', '同学', '正在努力的人'], ['鼓励打气', '毕业', '迎接新开始']
        else:
            recipients, occasions = ['朋友', '花卉爱好者', '自己'], ['生日祝福', '日常问候', '盆栽分享']
    return {'giftRecipients': recipients, 'giftOccasions': occasions}
